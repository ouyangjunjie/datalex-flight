function toAirport(row, region) {
  const [code, name, city, pinyin, airport, hot] = row
  return {
    code,
    name,
    city,
    pinyin,
    airport,
    hot: Boolean(hot),
    region,
    initial: (pinyin[0] || '').toUpperCase(),
    // 搜索用的扁平串：中文名 / 城市 / 拼音 / 三字码 / 机场全名
    searchText: `${code} ${name} ${city} ${pinyin} ${airport}`.toLowerCase(),
  }
}

